/* Word & Character Counter. Classic script (no modules), so it also works when the page is opened from file://. */
(function (g) {
  'use strict';
  function stats(t) {
    t = String(t == null ? '' : t);
    return {
      words: (t.trim().match(/\S+/g) || []).length,
      chars: [...t].length,
      charsNoSpaces: [...t.replace(/\s/g, '')].length,
      sentences: t.split(/[.!?]+(?:\s+|$)/).filter((s) => /\S/.test(s)).length,
      paragraphs: t.split(/\n\s*\n/).filter((p) => /\S/.test(p)).length,
      lines: t ? t.split(/\r?\n/).length : 0,
    };
  }
  const LABELS = [['words', 'Words'], ['chars', 'Characters (with spaces)'], ['charsNoSpaces', 'Characters (no spaces)'], ['sentences', 'Sentences'], ['paragraphs', 'Paragraphs'], ['lines', 'Lines']];
  const asText = (s) => LABELS.map(([k, l]) => `${l}: ${s[k]}`).join('\n');
  g.ET_WC = { stats, asText };
  if (typeof document === 'undefined') return;
  function init() {
    const U = g.ET_UI, inp = U.$('#in'), box = U.$('#stats');
    if (!inp || !box) { console.error('Word counter: required elements #in / #stats are missing.'); return; }
    let last = asText(stats(''));
    function update() {
      const s = stats(inp.value); last = asText(s);
      box.replaceChildren(...LABELS.map(([k, l]) => {
        const d = document.createElement('div'); d.className = 'stat'; d.append(l);
        const b = document.createElement('b'); b.textContent = s[k].toLocaleString('en-US'); d.append(b); return d;
      }));
      U.say(inp.value.trim() ? '' : 'Type or paste text above – counts update as you type.', 'info');
    }
    ['input', 'change', 'keyup', 'paste', 'cut'].forEach((ev) => inp.addEventListener(ev, () => (ev === 'paste' || ev === 'cut' ? setTimeout(update, 0) : update())));
    U.on('#apply', 'click', () => { update(); U.say('Counted.', 'ok'); });
    U.on('#copy', 'click', () => U.copy(last + (inp.value.trim() ? '\\n\\nText length summary generated by EverydayTools.' : '\\n\\nNo text entered.')));
    U.on('#dl', 'click', () => U.download(last + '\n', 'word-count-results.txt'));
    U.on('#reset', 'click', () => { inp.value = ''; update(); inp.focus(); });
    update();
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
})(typeof globalThis !== 'undefined' ? globalThis : window);
